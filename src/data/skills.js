/**
 * Get all skills as flat array
 */
export const getAllSkills = () => {
  return Object.values(skills).flat();
};

/**
 * Get skills by category
 * @param {string} category - Category key
 * @returns {Array} - Skills array
 */
export const getSkillsByCategory = (category) => {
  return skills[category] || [];
};

/**
 * Get top skills (by level)
 * @param {number} count - Number of skills to return
 * @returns {Array} - Top skills
 */
export const getTopSkills = (count = 10) => {
  return getAllSkills()
    .filter((skill) => skill.level)
    .sort((a, b) => b.level - a.level)
    .slice(0, count);
};

/**
 * Search skills by name
 * @param {string} query - Search query
 * @returns {Array} - Matching skills
 */
export const searchSkills = (query) => {
  const lowerQuery = query.toLowerCase();
  return getAllSkills().filter((skill) =>
    skill.name.toLowerCase().includes(lowerQuery)
  );
};

/**
 * Get category info by ID
 * @param {string} categoryId - Category ID
 * @returns {Object|null} - Category info
 */
export const getCategoryInfo = (categoryId) => {
  return skillCategories.find((cat) => cat.id === categoryId) || null;
};

/**
 * Calculate total years of experience (average)
 */
export const getTotalExperience = () => {
  const allSkills = getAllSkills().filter((skill) => skill.years);
  const totalYears = allSkills.reduce((sum, skill) => sum + skill.years, 0);
  return Math.round(totalYears / allSkills.length);
};

